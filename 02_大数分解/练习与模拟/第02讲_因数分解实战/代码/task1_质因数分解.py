n = int(input())
m = n
parts = []
i = 2
X = " × "
# 第 1 步：写外层循环 while i * i <= m:--只要候选 i 没超过平方根就继续找
# 第 2 步：写内层循环 while m % i == 0:--同一个因子反复除，循环体两行：
#             parts.append(str(i))   存因子（存文字，join 才能连）
#             m = m // i             整除更新，别写成 /
# 第 3 步：内层结束后退一层缩进写 i = i + 1，换下一个候选
# 第 4 步：外层结束后写质数边界：if m > 1: parts.append(str(m))
# 第 5 步：拼输出：print(str(n) + " = " + X.join(parts))
